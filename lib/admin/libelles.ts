function humaniser(cle: string): string {
  if (MOTS[cle]) return MOTS[cle];
  const mots = cle.replace(/([a-z])([A-Z])/g, "$1 $2").toLowerCase();
  return mots.charAt(0).toUpperCase() + mots.slice(1);
}

export function libelleDe(chemin: string): string {
  if (LIBELLES[chemin]) return LIBELLES[chemin];
  const dernier = chemin.match(/([A-Za-z]+)$|\[(\d+)\]$/);
  if (dernier?.[2] !== undefined) return `n° ${Number(dernier[2]) + 1}`;
  return humaniser(dernier?.[1] ?? chemin);
}

export function aideDe(chemin: string): string | undefined {
  return AIDES[chemin];
}

